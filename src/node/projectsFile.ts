// Changes to the project database file. These write to disk, so they live here and not in the
// browser code. The file is kept as the user wrote it: changes are appended, never rewritten.
import { existsSync, readFileSync, renameSync, statSync, writeFileSync } from "node:fs";
import { basename, dirname, join } from "node:path";

import { addProjectText, scalar } from "../core/projectsText";
import { Database, DbProject, loadDatabase } from "../core/reports";
import { formatMinutes } from "../core/summary";

export const BEGIN_MARK = "# --- unregistered projects (generated by time_parser; uncomment one to accept it) ---";
export const END_MARK = "# --- end of unregistered projects ---";
const BLOCK_HEADER = [
  "# These projects appear in the time entries but are not registered yet.",
  "# To accept one: uncomment its lines, change the name if needed, and set a category",
  "# (personal or professional) if you want one. Run `make sync-projects` again to add newly found projects.",
];

export interface Suggestion {
  text: string;
  minutes: number;
  entries: number;
}

export { scalar } from "../core/projectsText";

function writeAtomic(path: string, text: string): void {
  const temporary = join(dirname(path), `.${basename(path)}.tmp`);
  writeFileSync(temporary, text, "utf-8");
  renameSync(temporary, path);
}

function requireFile(path: string): void {
  if (!existsSync(path) || !statSync(path).isFile()) throw new Error(`${path}: project database not found`);
}

export function loadDatabaseFile(path: string): Database {
  return loadDatabase(readFileSync(path, "utf-8"), path);
}

// Appends a project to the database file, with keywords (default: its name). The result is
// checked before anything is written, so a clash or a reserved name leaves the file alone.
export function addProject(path: string, name: string, keywords?: string[]): DbProject {
  requireFile(path);
  const { text, project } = addProjectText(readFileSync(path, "utf-8"), name, keywords, path);
  writeAtomic(path, text);
  return project;
}

// Whether the file already mentions the project's name or one of its keywords, commented or not.
function mentions(lines: string[], text: string): boolean {
  const normal = (value: string) => value.trim().replace(/^["']+|["']+$/g, "").trim().toLowerCase();
  const wanted = normal(text);
  for (const line of lines) {
    const body = line.replace(/^#+/, "").split(" #")[0].trim(); // a trailing comment does not count
    if (body.endsWith(":") && normal(body.slice(0, -1)) === wanted) return true;
    if (body.startsWith("- ") && normal(body.slice(2)) === wanted) return true;
    if (body.startsWith("keywords:")) {
      const inside = body.slice("keywords:".length).trim().replace(/^\[+|\]+$/g, "");
      if (inside.split(",").some((item) => item.trim() && normal(item) === wanted)) return true;
    }
  }
  return false;
}

function suggestionLines(suggestion: Suggestion): string[] {
  const count = `${suggestion.entries} ${suggestion.entries === 1 ? "entry" : "entries"}`;
  const name = scalar(suggestion.text);
  return [
    `# ${formatMinutes(suggestion.minutes)}, ${count}`,
    `#${name}:`,
    "#  # category: personal | professional",
    "#  keywords:",
    `#    - ${name}`,
  ];
}

// Adds suggestions for projects not yet mentioned in the file. Never removes or changes a line.
// A new block is created at the end of the file when there is none. Returns how many were added.
export function syncSuggestions(path: string, suggestions: Suggestion[]): number {
  requireFile(path);
  const lines = readFileSync(path, "utf-8").split("\n");
  if (lines[lines.length - 1] === "") lines.pop();

  const fresh = suggestions.filter((suggestion) => !mentions(lines, suggestion.text));
  if (!fresh.length) return 0;
  const added = fresh.flatMap(suggestionLines);

  const begin = lines.indexOf(BEGIN_MARK);
  if (begin !== -1) {
    const end = lines.findIndex((line, index) => index > begin && line === END_MARK);
    if (end === -1) {
      throw new Error(`${path}: the generated block starts but never ends; add the '${END_MARK}' line after it`);
    }
    lines.splice(end, 0, ...added);
  } else {
    while (lines.length && !lines[lines.length - 1].trim()) lines.pop();
    if (lines.length) lines.push("");
    lines.push(BEGIN_MARK, ...BLOCK_HEADER, ...added, END_MARK);
  }
  writeAtomic(path, lines.length ? lines.join("\n") + "\n" : "");
  return fresh.length;
}
